/** 5문항씩 4개 축(E/I, S/N, T/F, J/P)으로 묶여 있으므로, 각 축에서 다수인 성향을 채택합니다. */
export function computeMbtiCode(traits) {
  let code = "";
  for (let group = 0; group < 4; group++) {
    const slice = traits.slice(group * 5, group * 5 + 5);
    const counts = {};
    slice.forEach((t) => {
      counts[t] = (counts[t] || 0) + 1;
    });
    const [winner] = Object.entries(counts).sort((a, b) => b[1] - a[1])[0];
    code += winner;
  }
  return code;
}
